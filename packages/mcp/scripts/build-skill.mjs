#!/usr/bin/env node
/**
 * Bundle the Deribit client plus the shared analytics into one dependency-free ES module
 * for the skill's scripts: plugins/deribit/skills/deribit/scripts/lib/deribit.mjs.
 *
 *   npm run build:skill          rebuild
 *   npm run build:skill -- --check  exit 1 if the checked-in bundle is stale (CI)
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..', '..');
const out = path.join(repo, 'plugins', 'deribit', 'skills', 'deribit', 'scripts', 'lib', 'deribit.mjs');

const entry = `
export * from 'deribit-client-js';
export * from './src/analytics.js';
export { toCsv } from './src/format.js';
`;

const result = await build({
  stdin: { contents: entry, resolveDir: path.resolve(here, '..'), loader: 'js' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  legalComments: 'none',
  banner: {
    js: '// Generated by packages/mcp/scripts/build-skill.mjs from deribit-client-js and packages/mcp/src/analytics.js. Do not edit.\n// Needs a runtime with global fetch and WebSocket (Node 22+, Deno, Bun).',
  },
});
const code = result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== code) {
    console.error(`${path.relative(repo, out)} is stale; run \`npm run build:skill\` in packages/mcp.`);
    process.exit(1);
  }
  console.log(`${path.relative(repo, out)} is up to date.`);
} else {
  await writeFile(out, code);
  console.log(`Wrote ${path.relative(repo, out)} (${(code.length / 1024).toFixed(0)} KB).`);
}
