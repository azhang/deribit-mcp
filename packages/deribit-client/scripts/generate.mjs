#!/usr/bin/env node
/**
 * Generate runtime metadata and TypeScript types from the vendored Deribit specs.
 *
 *   spec/deribit_openapi.json   -> src/generated/methods.js, src/generated/openapi.d.ts
 *   spec/deribit_asyncapi.json  -> src/generated/channels.js
 *
 * Update the specs with `npm run check-spec -- --write`, then re-run this script.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const specDir = path.join(root, 'spec');
const outDir = path.join(root, 'src', 'generated');

const openapi = JSON.parse(await readFile(path.join(specDir, 'deribit_openapi.json'), 'utf8'));
const asyncapi = JSON.parse(await readFile(path.join(specDir, 'deribit_asyncapi.json'), 'utf8'));

function resolve(spec, node) {
  const seen = new Set();
  while (node && typeof node === 'object' && node.$ref) {
    if (seen.has(node.$ref)) break;
    seen.add(node.$ref);
    node = node.$ref.split('/').slice(1).reduce((obj, key) => obj?.[key], spec);
  }
  return node;
}

/** Reduce a parameter schema to the parts the runtime validator and search use. */
function paramSchema(spec, schema) {
  schema = resolve(spec, schema) ?? {};
  const variants = schema.oneOf ?? schema.anyOf;
  if (variants) {
    return { oneOf: variants.map((v) => paramSchema(spec, v)) };
  }
  const out = {};
  if (schema.type) out.type = schema.type;
  if (schema.enum) out.enum = schema.enum;
  if (schema.type === 'array' && schema.items) out.items = paramSchema(spec, schema.items);
  return out;
}

function firstSentence(text = '') {
  const clean = text.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
  const match = clean.match(/^(.{20,300}?[.!?])(\s|$)/);
  return match ? match[1] : clean.slice(0, 300);
}

function plainText(text = '') {
  return text.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
}

// ---- Methods (OpenAPI) ----
const methods = {};
for (const [p, ops] of Object.entries(openapi.paths).sort(([a], [b]) => a.localeCompare(b))) {
  const op = ops.get;
  if (!op) continue;
  const name = p.replace(/^\//, '');
  const params = {};
  const required = [];
  for (const raw of op.parameters ?? []) {
    const param = resolve(openapi, raw);
    params[param.name] = {
      ...paramSchema(openapi, param.schema),
      description: plainText(param.description ?? resolve(openapi, param.schema)?.description ?? ''),
    };
    if (param.required) required.push(param.name);
  }
  methods[name] = {
    scope: name.startsWith('private/') ? 'private' : 'public',
    tags: op.tags ?? [],
    summary: firstSentence(op.description),
    description: plainText(op.description),
    deprecated: Boolean(op.deprecated),
    params,
    required,
  };
}

// ---- Channels (AsyncAPI) ----
const channels = {};
for (const [key, ch] of Object.entries(asyncapi.channels).sort(([a], [b]) => a.localeCompare(b))) {
  const params = {};
  for (const [name, def] of Object.entries(ch.parameters ?? {})) {
    params[name] = { description: plainText(def.description ?? '') };
    if (def.enum) params[name].enum = def.enum;
  }
  const tags = (ch.tags ?? []).map((t) => t.name);
  channels[ch.address ?? key] = {
    // Template uses {param} placeholders: "ticker.{instrument_name}.{interval}"
    template: (ch.address ?? key).replace(/\(([^)]+)\)/g, '{$1}'),
    scope: tags.includes('Private') ? 'private' : 'public',
    tags,
    summary: firstSentence(ch.summary ?? ch.description),
    params,
  };
}

const header = (src) =>
  `// Generated by scripts/generate.mjs from ${src} (Deribit API ${openapi.info.version}). Do not edit.\n`;

await writeFile(
  path.join(outDir, 'methods.js'),
  header('spec/deribit_openapi.json') +
    `/** @type {Record<string, import('../index.js').MethodInfo>} */\n` +
    `export const methods = ${JSON.stringify(methods, null, 1)};\n` +
    `export const apiVersion = ${JSON.stringify(openapi.info.version)};\n`,
);
await writeFile(
  path.join(outDir, 'channels.js'),
  header('spec/deribit_asyncapi.json') +
    `/** @type {Record<string, import('../index.js').ChannelInfo>} */\n` +
    `export const channels = ${JSON.stringify(channels, null, 1)};\n`,
);

// ---- Types (openapi-typescript) ----
execFileSync(
  process.execPath,
  [
    path.join(root, 'node_modules', 'openapi-typescript', 'bin', 'cli.js'),
    path.join(specDir, 'deribit_openapi.json'),
    '--output',
    path.join(outDir, 'openapi.d.ts'),
  ],
  { stdio: 'inherit' },
);

const publicCount = Object.values(methods).filter((m) => m.scope === 'public').length;
console.log(
  `Generated ${Object.keys(methods).length} methods (${publicCount} public) and ${Object.keys(channels).length} channels.`,
);
